// Emits the generated Twenty client into packages/core so every surface
// (CLI, API, MCP, Convex actions) issues typed GraphQL queries and mutations
// instead of hand-rolled REST with envelope guessing.
//
// The approach mirrors twenty-coach's emit-api-client: the workspace's own
// GraphQL schema is the source of truth, so custom `agency*` objects arrive
// with exact types. Differences here are deliberate:
//   - SDL comes from introspecting the live instance (we have no twenty-app
//     object sources in this repo; the workspace IS the schema), and
//   - no wrapper template is skipped: with clientWrapperTemplateSource ''
//     the output is the bare genql client, whose auth is injected per call
//     by twenty/api's authorizedFetch (OAuth tokens, refresh on expiry).
//
// Two repo-convention fixes are applied to the generator's raw output:
//   - relative specifiers end in .ts, because this repo runs from source
//     (tsc with allowImportingTsExtensions, tsx, vitest) and never emits JS;
//     the generator writes .js, which only resolves after a build step.
//   - every file is stamped with an `@generated` header, which is also the
//     marker scripts/check-no-font-mono.mjs uses to skip machine-written
//     files (a workspace enum value happens to be 'MONACO').
//
// Usage:
//   TWENTY_BASE_URL=... TWENTY_API_KEY=... pnpm twenty:client [--check]
//   pnpm twenty:client --schema path/to/schema.graphql   (offline, from SDL)
// TWENTY_CLIENT_OUT=<dir> redirects the target, which is how the emit path is
// exercised without credentials or without overwriting the committed tree.
// --check regenerates to a temp dir and fails when the committed tree is
// stale, missing a file, or holding a file the generator no longer emits, so
// CI catches schema drift without needing credentials to build.
import { mkdtemp, readdir, readFile, rm, writeFile, mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildClientSchema, getIntrospectionQuery, printSchema } from "graphql";
import { generateCoreClientFromSchema } from "twenty-client-sdk/generate";

const here = dirname(fileURLToPath(import.meta.url));
const TARGET_DIR = process.env.TWENTY_CLIENT_OUT
  ? resolve(process.env.TWENTY_CLIENT_OUT)
  : join(here, "../packages/core/src/twenty/api/generated");
const HEADER = `// @generated by \`pnpm twenty:client\` - do not edit by hand.
// Source: introspection of the configured Twenty workspace. Refresh with the
// same command whenever custom objects or fields change.
// @ts-nocheck
`;

const isSource = (name) => name.endsWith(".ts") || name.endsWith(".tsx");

/** Point relative imports at this repo's .ts source files, not built .js. */
const toTypeScriptSpecifiers = (content) =>
  content.replace(/(from\s+'\.[^']*)\.js'/g, "$1.ts'");

/** Some generator versions stamp their own @ts-nocheck; the header owns it. */
const withoutOwnTsNocheck = (content) => content.replace(/^\/\/ @ts-nocheck\n/, "");

async function collect(dir, base = dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collect(path, base)));
    } else if (isSource(entry.name)) {
      const body = toTypeScriptSpecifiers(withoutOwnTsNocheck(await readFile(path, "utf8")));
      files.push([relative(base, path), HEADER + body]);
    }
  }
  return files.sort(([a], [b]) => a.localeCompare(b));
}

async function introspect(baseUrl, apiKey) {
  const url = `${baseUrl.replace(/\/+$/, "")}/graphql`;
  const response = await fetch(url, {
    method: "POST",
    headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
    body: JSON.stringify({ query: getIntrospectionQuery() }),
  });
  if (!response.ok) {
    console.error(`Introspection failed: HTTP ${response.status} from ${url}.`);
    process.exit(1);
  }
  const body = await response.json();
  if (body.errors?.length || !body.data) {
    console.error(`Introspection errors: ${JSON.stringify(body.errors ?? "empty response").slice(0, 500)}`);
    process.exit(1);
  }
  return printSchema(buildClientSchema(body.data));
}

async function readSchema() {
  const flag = process.argv.indexOf("--schema");
  if (flag !== -1) {
    const path = process.argv[flag + 1];
    if (!path) {
      console.error("--schema needs a path to a schema.graphql file.");
      process.exit(1);
    }
    return readFile(path, "utf8");
  }
  const baseUrl = process.env.TWENTY_BASE_URL;
  const apiKey = process.env.TWENTY_API_KEY;
  if (!baseUrl || !apiKey) {
    console.error(
      "TWENTY_BASE_URL and TWENTY_API_KEY are required to emit the Twenty client.\n" +
        "To work from a saved schema instead, pass --schema path/to/schema.graphql.",
    );
    process.exit(1);
  }
  return introspect(baseUrl, apiKey);
}

/** Generated file names currently on disk, for stale-extra detection. */
async function existingFiles(dir) {
  try {
    return (await collect(dir)).map(([name]) => name);
  } catch {
    return [];
  }
}

const schema = await readSchema();
const scratch = await mkdtemp(join(tmpdir(), "blaster-twenty-client-"));
await generateCoreClientFromSchema({ schema, outputPath: scratch, clientWrapperTemplateSource: "" });
const emitted = await collect(scratch);
await rm(scratch, { recursive: true, force: true });

if (process.argv.includes("--check")) {
  const names = emitted.map(([name]) => name);
  let stale = false;
  for (const [name, content] of emitted) {
    if ((await readFile(join(TARGET_DIR, name), "utf8").catch(() => "")) !== content) {
      console.error(`${name} is stale - run \`pnpm twenty:client\` with instance credentials and commit the result.`);
      stale = true;
    }
  }
  for (const name of (await existingFiles(TARGET_DIR)).filter((f) => !names.includes(f))) {
    console.error(`${name} is no longer emitted by the generator - delete it.`);
    stale = true;
  }
  if (stale) process.exit(1);
  console.log(`Generated Twenty client is up to date (${names.length} files).`);
} else {
  await rm(TARGET_DIR, { recursive: true, force: true });
  for (const [name, content] of emitted) {
    const path = join(TARGET_DIR, name);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
  console.log(`Wrote ${emitted.length} files to ${TARGET_DIR}`);
}
