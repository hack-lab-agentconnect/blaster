// Emits config/twenty-objects.json: the Twenty object names this repository is
// allowed to mirror in a domain directory.
//
// Why this file exists: the naming convention says a module that mirrors an
// external system keeps that system's spelling, and Twenty's objects are
// camelCase (`agencyPhone`, `workspaceMember`). The naming gate needs to know
// which camelCase names are legitimate, or it either rejects every mirror or
// accepts any camelCase at all. This list is the allowlist.
//
// It is checked in on purpose. The gate runs pre-push and must stay offline and
// deterministic, so it reads this file rather than calling Twenty.
//
// Names are derived from packages/core/src/twenty/api/generated/schema.ts, which
// is itself generated by `pnpm twenty:client` from an introspection of the live
// workspace. So the list is downstream of the same authority the sibling dialer
// repo documents (Twenty's own schema), with no second credential path and no
// network at gate time. Refresh it whenever the objects change, in the same
// commit that renames a domain:
//
//   node scripts/emit-twenty-objects.mjs            # derive from the schema
//   node scripts/emit-twenty-objects.mjs --check    # fail when stale
//
// Mirrored modules that are Twenty concepts rather than objects (`objectService`,
// `actor`) are listed with their origin recorded, so the gate can tell a
// legitimate camelCase directory from a typo.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const TARGET = join(here, "../config/twenty-objects.json");
const SCHEMA = join(here, "../packages/core/src/twenty/api/generated/schema.ts");

/**
 * Mirrors that are Twenty concepts rather than Twenty objects. `objectService`
 * is Twenty's own name for its object-metadata surface, and `actor` mirrors the
 * `ACTOR` field type Twenty stamps on every record. They are listed with their
 * origin so the gate can tell a deliberate mirror from a typo, and so a reader
 * can see why a camelCase directory is legal.
 */
const CONCEPT_MIRRORS = [
  { name: "actor", origin: "Twenty field type ACTOR, on every record's createdBy/updatedBy" },
  { name: "objectService", origin: "Twenty's object-metadata surface (objects { nameSingular })" },
];

/**
 * Twenty's nameSingular from the generated schema.
 *
 * Every Twenty object is reachable from the root Query as `<plural>?: <Type>Connection`,
 * and the object type is declared as `export interface <Type> {` with the standard
 * record fields. Requiring both is what keeps this precise: a bare `Connection`
 * match would also catch join tables, and a bare `interface` match would catch
 * every input and enum in the schema. The object type is PascalCase, and
 * Twenty's nameSingular is that name with a lowercase first letter, so the
 * singular is derived rather than guessed.
 */
async function objectsFromSchema() {
  const schema = await readFile(SCHEMA, "utf8");
  const declared = new Set(
    [...schema.matchAll(/^export interface (\w+) \{/gm)].map((match) => match[1]),
  );
  const singulars = new Set();
  for (const match of schema.matchAll(/^\s+(\w+)\??: (\w+)Connection\b/gm)) {
    const objectType = match[2];
    if (!declared.has(objectType)) continue;
    singulars.add(objectType.charAt(0).toLowerCase() + objectType.slice(1));
  }
  if (singulars.size === 0) {
    console.error(
      `No Twenty objects found in ${SCHEMA}.\n` +
        "Either the schema moved or the generator's output shape changed; both mean the\n" +
        "derivation above needs updating rather than silently emitting an empty list.",
    );
    process.exit(1);
  }
  return [...singulars].sort();
}

function serialise(singulars) {
  const objects = [...new Set([...singulars, ...CONCEPT_MIRRORS.map((mirror) => mirror.name)])].sort();
  const mirrors = {};
  for (const mirror of CONCEPT_MIRRORS) mirrors[mirror.name] = mirror.origin;
  return `${JSON.stringify(
    {
      $comment:
        "Twenty nameSingular values, plus the Twenty concepts this repo mirrors. A camelCase domain directory is legal only when it appears here. Regenerate with `pnpm twenty:objects`.",
      derivedFrom: "packages/core/src/twenty/api/generated/schema.ts",
      objects,
      conceptMirrors: mirrors,
    },
    null,
    2,
  )}\n`;
}

const next = serialise(await objectsFromSchema());

if (process.argv.includes("--check")) {
  const committed = await readFile(TARGET, "utf8").catch(() => "");
  if (committed !== next) {
    console.error(
      "config/twenty-objects.json is stale - run `pnpm twenty:objects` and commit the result.",
    );
    process.exit(1);
  }
  console.log("Twenty object list is up to date.");
} else {
  await writeFile(TARGET, next, "utf8");
  console.log(`Wrote ${JSON.parse(next).objects.length} Twenty object names to config/twenty-objects.json`);
}
